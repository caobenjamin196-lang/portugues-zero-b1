for wk in ("w1", "w2", "w3", "w4"):
    path = os.path.join(ROOT, "exercises", f"w0{wk[1]}-quiz.json")
    with open(path, encoding="utf-8") as f:
        quiz = json.load(f)
    converted = 0
    for q in quiz["questions"]:
        conv = CONVERT.get(wk, {}).get(q["id"])
        if conv and q["type"] == "fill_blank":
            q["type"] = "single_choice"
            q["prompt"] = conv["prompt"]
            q["options"] = conv["options"]
            q["answer"] = conv["answer"]
            q.pop("hint", None) if conv.get("drop_hint") else None
            converted += 1
    quiz["questions"].extend(VOCAB[wk])
    with open(path, "w", encoding="utf-8") as f:
        json.dump(quiz, f, ensure_ascii=False, indent=2)
        f.write("\n")
    # 统计
    qs = quiz["questions"]
    total = len(qs)
    choice = sum(1 for q in qs if q["type"] in ("single_choice", "multi_choice"))
    vocab = sum(1 for q in qs if q["id"].startswith(f"{wk}_vocab_"))
    print(f"{wk}: 转换 {converted} 题, 新增词汇题 {vocab} 题, 总题数 {total}, 选择题 {choice} ({choice/total*100:.0f}%)")
