# ============ 生成 JSON ============
def build_entry(t):
    rank, pt, pos, zh, xpt, xzh, ff, vb = t
    e = {"rank": rank, "pt": pt, "pos": pos, "zh": zh,
         "example": {"pt": xpt, "zh": xzh}}
    if ff:
        e["falseFriend"] = ff
    if vb:
        meaning, vtype, es_inf, note = VERBS[vb]
        c = conj_pt(vb)
        conj = {"eu": c[0], "tu": c[1], "ele/ela/você": c[2], "nós": c[3], "eles/elas/vocês": c[4]}
        conj["es"] = es_line(es_inf) if es_inf else note.split("——")[0]
        e["conjugations"] = conj
    return e

freq = {
    "description": "每周 100 个频率词汇（PT-BR）。W1=频率排名1-100，W2=101-200，W3=201-300，W4=301-400。选词参考 Corpus do Português / Routledge Frequency Dictionary 高频区。动词附现在时完整变位与西语对照；falseFriend 为西语假朋友警示。",
    "source": "Corpus do Português / Routledge Frequency Dictionary of Portuguese（高频区，按教学需要微调）",
    "variant": "PT-BR",
    "w1": [build_entry(t) for t in W1],
    "w2": [build_entry(t) for t in W2],
    "w3": [build_entry(t) for t in W3],
    "w4": [build_entry(t) for t in W4],
}

# 动词变位总表（沿用原 data/verb-conjugations.json 格式）
verbs_out = []
for week in (W1, W2, W3, W4):
    for t in week:
        vb = t[7]
        if not vb:
            continue
        meaning, vtype, es_inf, note = VERBS[vb]
        c = conj_pt(vb)
        v = {
            "infinitive": vb,
            "meaning": meaning,
            "type": vtype,
            "conjugation": {"eu": c[0], "tu": c[1], "ele/ela/você": c[2], "nós": c[3], "eles/elas/vocês": c[4]},
            "spanish": es_line(es_inf) if es_inf else note.split("——")[0],
        }
        if note:
            v["note"] = note
        verbs_out.append(v)

