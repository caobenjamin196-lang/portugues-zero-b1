def conj_pt(inf):
    """规则动词现在时变位（含拼写变化 -cer→-ço、-ger/-gir→-jo）"""
    if inf in PT_IRREG:
        return PT_IRREG[inf]
    stem, end = inf[:-2], inf[-2:]
    if end == "ar":
        endings = ["o", "as", "a", "amos", "am"]
    elif end == "er":
        endings = ["o", "es", "e", "emos", "em"]
    else:
        endings = ["o", "es", "e", "imos", "em"]
    forms = [stem + e for e in endings]
    eu = forms[0]
    if stem.endswith("c"):       # esquecer→esqueço, conhecer→conheço, parecer→pareço
        eu = stem[:-1] + "ço"
    elif stem.endswith("g") and end in ("er", "ir"):  # dirigir→dirijo, proteger→protejo
        eu = stem[:-1] + "jo"
    forms[0] = eu
    return forms

